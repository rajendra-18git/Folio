import time
from typing import Optional, Tuple, Dict, Any, List
from app.core.config import (
    get_effective_gemini_key,
    get_effective_gemini_model,
    set_runtime_gemini_model,
    settings
)

try:
    from google import genai
    from google.genai import types
    GENAI_SDK_AVAILABLE = True
except ImportError:
    GENAI_SDK_AVAILABLE = False

class AIProviderService:
    def __init__(self):
        pass

    def is_configured(self, api_key: Optional[str] = None) -> bool:
        """Returns True if a valid Gemini API key is available and SDK is installed."""
        key = (api_key.strip() if api_key else None) or get_effective_gemini_key()
        return bool(key and key.strip() and GENAI_SDK_AVAILABLE)

    def get_client(self, api_key: Optional[str] = None):
        if not self.is_configured(api_key=api_key):
            return None
        key = (api_key.strip() if api_key else None) or get_effective_gemini_key()
        return genai.Client(api_key=key)

    def get_user_ai_credentials(self, db, user_id: Optional[str]) -> Tuple[Optional[str], Optional[str]]:
        """Returns (api_key, model_name) for a specific user."""
        if user_id:
            try:
                from app.models.db_models import User
                user = db.query(User).filter(User.id == user_id).first()
                if user:
                    user_key = user.gemini_api_key.strip() if user.gemini_api_key else None
                    user_model = user.gemini_model.strip() if user.gemini_model else None
                    return user_key, (user_model or get_effective_gemini_model())
            except Exception:
                pass
        return get_effective_gemini_key(), get_effective_gemini_model()

    def _get_candidate_models(self, preferred_model: Optional[str] = None) -> List[str]:
        chosen = preferred_model or get_effective_gemini_model()
        fallbacks = [chosen, "gemini-flash-latest", "gemini-3.8-flash", "gemini-3.7-flash", "gemini-3.5-flash", "gemini-pro-latest"]
        # Deduplicate while preserving order
        seen = set()
        unique = []
        for m in fallbacks:
            if m and m not in seen:
                seen.add(m)
                unique.append(m)
        return unique

    def generate_text(
        self,
        prompt: str,
        system_instruction: Optional[str] = None,
        model_name: Optional[str] = None,
        api_key: Optional[str] = None
    ) -> Tuple[str, Dict[str, Any]]:
        """
        Generates text using Google Gemini with automatic model fallback.
        Returns:
            text: generated string
            metrics: {"latency_ms": float, "tokens_used": int, "is_demo": bool}
        """
        start_time = time.time()

        if not self.is_configured(api_key=api_key):
            # Local retrieval-only / demo fallback
            latency = (time.time() - start_time) * 1000
            return (
                "⚠️ **Direct Document Retrieval Mode (AI API Key Not Configured)**\n\n"
                "To unlock live GenAI answers with deep reasoning, please configure your AI API Key in the **Settings** tab or in the `.env` file.\n\n"
                "Here are the grounded source passages directly retrieved from your documents for this query:\n\n"
                f"{prompt}",
                {"latency_ms": latency, "tokens_used": 0, "is_demo": True}
            )

        client = self.get_client(api_key=api_key)
        config = types.GenerateContentConfig(
            system_instruction=system_instruction if system_instruction else None,
            temperature=0.2,
        )

        candidates = self._get_candidate_models(model_name)
        last_error = None

        for candidate in candidates:
            try:
                response = client.models.generate_content(
                    model=candidate,
                    contents=prompt,
                    config=config
                )
                latency = (time.time() - start_time) * 1000

                # If successful and was a fallback, remember candidate model
                set_runtime_gemini_model(candidate)

                tokens = 0
                if hasattr(response, "usage_metadata") and response.usage_metadata:
                    tokens = getattr(response.usage_metadata, "total_token_count", 0) or (
                        (getattr(response.usage_metadata, "prompt_token_count", 0) or 0) +
                        (getattr(response.usage_metadata, "candidates_token_count", 0) or 0)
                    )

                text = response.text if response.text else "No response generated by model."
                if not tokens:
                    tokens = max(1, int((len(prompt) + len(text)) / 4))
                return text, {"latency_ms": latency, "tokens_used": tokens, "is_demo": False, "model": candidate}

            except Exception as e:
                err_str = str(e)
                last_error = err_str
                # If model is 404 or unsupported for this account, continue to next candidate
                if "404" in err_str or "NOT_FOUND" in err_str or "no longer available" in err_str:
                    continue
                else:
                    # Non-404 error (e.g. quota, auth)
                    break

        latency = (time.time() - start_time) * 1000
        return (
            f"⚠️ **AI Engine Service Notice:** {last_error}\n\n"
            "Please verify your API key and permissions in Settings.",
            {"latency_ms": latency, "tokens_used": 0, "is_demo": True, "error": last_error}
        )

    def generate_multimodal(
        self,
        image_bytes: bytes,
        prompt: str,
        mime_type: str = "image/png",
        api_key: Optional[str] = None,
        model_name: Optional[str] = None
    ) -> Tuple[str, Dict[str, Any]]:
        """
        Visual reasoning on page images.
        """
        start_time = time.time()
        if not self.is_configured(api_key=api_key):
            latency = (time.time() - start_time) * 1000
            return (
                "Visual analysis requires a configured AI API Key. Please add your key in Settings or `.env`.",
                {"latency_ms": latency, "tokens_used": 0, "is_demo": True}
            )

        client = self.get_client(api_key=api_key)
        candidates = self._get_candidate_models(model_name)
        last_error = None

        image_part = types.Part.from_bytes(data=image_bytes, mime_type=mime_type)

        for candidate in candidates:
            try:
                response = client.models.generate_content(
                    model=candidate,
                    contents=[prompt, image_part]
                )
                latency = (time.time() - start_time) * 1000
                tokens = 0
                if hasattr(response, "usage_metadata") and response.usage_metadata:
                    tokens = getattr(response.usage_metadata, "total_token_count", 0) or (
                        (getattr(response.usage_metadata, "prompt_token_count", 0) or 0) +
                        (getattr(response.usage_metadata, "candidates_token_count", 0) or 0)
                    )

                set_runtime_gemini_model(candidate)
                resp_text = response.text or "No visual insights extracted."
                if not tokens:
                    tokens = 258 + max(1, int((len(prompt) + len(resp_text)) / 4))
                return resp_text, {
                    "latency_ms": latency,
                    "tokens_used": tokens,
                    "is_demo": False,
                    "model": candidate
                }
            except Exception as e:
                err_str = str(e)
                last_error = err_str
                if "404" in err_str or "NOT_FOUND" in err_str:
                    continue
                else:
                    break

        latency = (time.time() - start_time) * 1000
        return f"Multimodal analysis error: {last_error}", {
            "latency_ms": latency,
            "tokens_used": 0,
            "is_demo": True,
            "error": last_error
        }

    def _generate_fallback_embedding(self, text: str, dim: int = 768) -> List[float]:
        """Generates a deterministic L2-normalized 768-dim vector for test/demo mode."""
        import hashlib
        import math
        vec = [0.0] * dim
        words = text.lower().split()
        if not words:
            words = ["empty"]
        for w in words:
            h = int(hashlib.md5(w.encode("utf-8")).hexdigest(), 16) % dim
            vec[h] += 1.0
        norm = math.sqrt(sum(x * x for x in vec)) or 1.0
        return [float(x / norm) for x in vec]

    def get_embeddings(self, texts: List[str], api_key: Optional[str] = None) -> List[List[float]]:
        """
        Generates vector embeddings for a batch of text chunks.
        Uses Gemini text-embedding-004 if configured, with deterministic fallback.
        """
        if not texts:
            return []

        if self.is_configured(api_key=api_key):
            try:
                client = self.get_client(api_key=api_key)
                # Batch embed (batches of 16 to avoid payload limits)
                results = []
                batch_size = 16
                for i in range(0, len(texts), batch_size):
                    batch = texts[i:i + batch_size]
                    response = client.models.embed_content(
                        model="text-embedding-004",
                        contents=batch
                    )
                    if hasattr(response, "embeddings") and response.embeddings:
                        results.extend([list(e.values) for e in response.embeddings])
                    elif hasattr(response, "embedding") and response.embedding:
                        results.append(list(response.embedding.values))
                    else:
                        for t in batch:
                            results.append(self._generate_fallback_embedding(t))
                if len(results) == len(texts):
                    return results
            except Exception as e:
                print(f"[AIProvider] Live embedding generation fallback: {e}")

        return [self._generate_fallback_embedding(t) for t in texts]

    def get_embedding(self, text: str, api_key: Optional[str] = None) -> List[float]:
        """Generates a vector embedding for a single text query."""
        res = self.get_embeddings([text], api_key=api_key)
        return res[0] if res else self._generate_fallback_embedding(text)

ai_provider = AIProviderService()

