import time
from typing import Optional, Tuple, Dict, Any, List
from app.core.config import (
    get_effective_gemini_key,
    get_effective_gemini_model,
    set_runtime_gemini_model,
    settings
)

try:
    from google import genai
    from google.genai import types
    GENAI_SDK_AVAILABLE = True
except ImportError:
    GENAI_SDK_AVAILABLE = False

class AIProviderService:
    def __init__(self):
        pass

    def is_configured(self) -> bool:
        """Returns True if a valid Gemini API key is available and SDK is installed."""
        key = get_effective_gemini_key()
        return bool(key and key.strip() and GENAI_SDK_AVAILABLE)

    def get_client(self):
        if not self.is_configured():
            return None
        key = get_effective_gemini_key()
        return genai.Client(api_key=key)

    def _get_candidate_models(self, preferred_model: Optional[str] = None) -> List[str]:
        chosen = preferred_model or get_effective_gemini_model()
        fallbacks = [chosen, "gemini-flash-latest", "gemini-3.8-flash", "gemini-3.7-flash", "gemini-3.5-flash", "gemini-pro-latest"]
        # Deduplicate while preserving order
        seen = set()
        unique = []
        for m in fallbacks:
            if m and m not in seen:
                seen.add(m)
                unique.append(m)
        return unique

    def generate_text(
        self,
        prompt: str,
        system_instruction: Optional[str] = None,
        model_name: Optional[str] = None
    ) -> Tuple[str, Dict[str, Any]]:
        """
        Generates text using Google Gemini with automatic model fallback.
        Returns:
            text: generated string
            metrics: {"latency_ms": float, "tokens_used": int, "is_demo": bool}
        """
        start_time = time.time()

        if not self.is_configured():
            # Local retrieval-only / demo fallback
            latency = (time.time() - start_time) * 1000
            return (
                "⚠️ **Direct Document Retrieval Mode (AI API Key Not Configured)**\n\n"
                "To unlock live GenAI answers with deep reasoning, please configure your AI API Key in the **Settings** tab or in the `.env` file.\n\n"
                "Here are the grounded source passages directly retrieved from your documents for this query:\n\n"
                f"{prompt}",
                {"latency_ms": latency, "tokens_used": 0, "is_demo": True}
            )

        client = self.get_client()
        config = types.GenerateContentConfig(
            system_instruction=system_instruction if system_instruction else None,
            temperature=0.2,
        )

        candidates = self._get_candidate_models(model_name)
        last_error = None

        for candidate in candidates:
            try:
                response = client.models.generate_content(
                    model=candidate,
                    contents=prompt,
                    config=config
                )
                latency = (time.time() - start_time) * 1000

                # If successful and was a fallback, remember candidate model
                set_runtime_gemini_model(candidate)

                tokens = 0
                if hasattr(response, "usage_metadata") and response.usage_metadata:
                    tokens = getattr(response.usage_metadata, "total_token_count", 0) or (
                        (getattr(response.usage_metadata, "prompt_token_count", 0) or 0) +
                        (getattr(response.usage_metadata, "candidates_token_count", 0) or 0)
                    )

                text = response.text if response.text else "No response generated by model."
                if not tokens:
                    tokens = max(1, int((len(prompt) + len(text)) / 4))
                return text, {"latency_ms": latency, "tokens_used": tokens, "is_demo": False, "model": candidate}

            except Exception as e:
                err_str = str(e)
                last_error = err_str
                # If model is 404 or unsupported for this account, continue to next candidate
                if "404" in err_str or "NOT_FOUND" in err_str or "no longer available" in err_str:
                    continue
                else:
                    # Non-404 error (e.g. quota, auth)
                    break

        latency = (time.time() - start_time) * 1000
        return (
            f"⚠️ **AI Engine Service Notice:** {last_error}\n\n"
            "Please verify your API key and permissions in Settings.",
            {"latency_ms": latency, "tokens_used": 0, "is_demo": True, "error": last_error}
        )

    def generate_multimodal(
        self,
        image_bytes: bytes,
        prompt: str,
        mime_type: str = "image/png"
    ) -> Tuple[str, Dict[str, Any]]:
        """
        Visual reasoning on page images.
        """
        start_time = time.time()
        if not self.is_configured():
            latency = (time.time() - start_time) * 1000
            return (
                "Visual analysis requires a configured AI API Key. Please add your key in Settings or `.env`.",
                {"latency_ms": latency, "tokens_used": 0, "is_demo": True}
            )

        client = self.get_client()
        candidates = self._get_candidate_models()
        last_error = None

        image_part = types.Part.from_bytes(data=image_bytes, mime_type=mime_type)

        for candidate in candidates:
            try:
                response = client.models.generate_content(
                    model=candidate,
                    contents=[prompt, image_part]
                )
                latency = (time.time() - start_time) * 1000
                tokens = 0
                if hasattr(response, "usage_metadata") and response.usage_metadata:
                    tokens = getattr(response.usage_metadata, "total_token_count", 0) or (
                        (getattr(response.usage_metadata, "prompt_token_count", 0) or 0) +
                        (getattr(response.usage_metadata, "candidates_token_count", 0) or 0)
                    )

                set_runtime_gemini_model(candidate)
                resp_text = response.text or "No visual insights extracted."
                if not tokens:
                    tokens = 258 + max(1, int((len(prompt) + len(resp_text)) / 4))
                return resp_text, {
                    "latency_ms": latency,
                    "tokens_used": tokens,
                    "is_demo": False,
                    "model": candidate
                }
            except Exception as e:
                err_str = str(e)
                last_error = err_str
                if "404" in err_str or "NOT_FOUND" in err_str:
                    continue
                else:
                    break

        latency = (time.time() - start_time) * 1000
        return f"Multimodal analysis error: {last_error}", {
            "latency_ms": latency,
            "tokens_used": 0,
            "is_demo": True,
            "error": last_error
        }

ai_provider = AIProviderService()
